def print_budget_summary(races):
    print()
    print("=" * 70)
    print("  💰 資金配分サマリー（予算: 10,000円）")
    print("=" * 70)
    total = 0
    for race in races:
        if race.budget > 0:
            total += race.budget
            bar = "█" * (race.budget // 100)
            print(f"  {race.race_num:>2}R [{race.start_time}] ¥{race.budget:>5,} {bar}")
    print(f"  {'─' * 40}")
    print(f"  合計: ¥{total:,}")
    remaining = 10000 - total
    if remaining > 0:
        print(f"  予備: ¥{remaining:,}（当日の状況で追加投資用）")


